#!/usr/bin/env node
// Build every app icon from the SVG sources in assets/icon/, in one command: npm run icons
// (needs the dev dependencies: npm install).
//
//   1. Outline the text in icon-master.svg and icon-small.svg (the S, in Space Grotesk Bold) into
//      *-outlined.svg, so no renderer needs the font. Derive icon-maskable.svg from the master's
//      "art" group, scaled to 72% for Android's safe zone.
//   2. Check every colour is a Wasabi and Nori token (site/css/tokens.css).
//   3. Render the PNGs (resvg) into site/icons/, write site/favicon.ico and site/icons/favicon.svg.
//   4. Generate the header mark (site/js/ui/brand-mark.js) with token colours.
//   5. Draw the iPhone launch screens and docs/screenshots/icon/contact-sheet.png for review.
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { deflateSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { readTokens } from './check-contrast.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const at = (p) => `${ROOT}/${p}`;
const SRC = 'assets/icon';
// Fonts the sources may use, by family and weight (OFL, from the @fontsource dev dependencies).
const FONTS = {
  'Space Grotesk': { 700: 'node_modules/@fontsource/space-grotesk/files/space-grotesk-latin-700-normal.woff' },
};

let opentype;
let Resvg;
try {
  const ot = await import('opentype.js');
  opentype = ot.default || ot;
  ({ Resvg } = (await import('@resvg/resvg-js')).default || (await import('@resvg/resvg-js')));
  for (const weights of Object.values(FONTS)) for (const file of Object.values(weights)) readFileSync(at(file));
} catch {
  console.error('Missing dev dependencies. Run `npm install` first (opentype.js, @fontsource/space-grotesk, @resvg/resvg-js).');
  process.exit(1);
}
const loaded = new Map();
function fontFor(family, weight) {
  const file = FONTS[family]?.[weight];
  if (!file) throw new Error(`no outline font for ${family} ${weight}; add it to FONTS`);
  if (!loaded.has(file)) {
    const buf = readFileSync(at(file));
    loaded.set(file, opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)));
  }
  return loaded.get(file);
}
const LABEL_FONT = fontFor('Space Grotesk', 700);

const tokens = readTokens();
const { light, dark } = tokens;
// Every colour the icon may use, by token. The header mark swaps each for var(--token).
const ICON_TOKENS = ['--wasabi', '--nori', '--paper', '--rice'];
const TOKEN_FOR = Object.fromEntries(ICON_TOKENS.map((t) => [light[t].toUpperCase(), t]));
const PALETTE = new Set([...Object.values(light), ...Object.values(dark)].filter((v) => /^#[0-9a-f]{6}$/i.test(v || '')).map((v) => v.toUpperCase()));

// ---------- 1. text to outlines ----------

const attrsOf = (s) => Object.fromEntries([...s.matchAll(/([\w:-]+)="([^"]*)"/g)].map(([, k, v]) => [k, v]));
const TEXT_ATTRS = new Set(['x', 'y', 'text-anchor', 'font-family', 'font-size', 'font-weight', 'letter-spacing']);

/** Path commands to SVG path data. (opentype.js 2's own toPathData can emit NaN for valid
 *  commands, so serialise them here; each contour is closed explicitly.) */
const num = (n) => { const r = Math.round(n * 100) / 100; return Object.is(r, -0) ? '0' : String(r); };
function pathData(commands) {
  let d = '';
  for (const c of commands) {
    if (c.type === 'M') d += `${d ? 'Z' : ''}M${num(c.x)} ${num(c.y)}`;
    else if (c.type === 'L') d += `L${num(c.x)} ${num(c.y)}`;
    else if (c.type === 'Q') d += `Q${num(c.x1)} ${num(c.y1)} ${num(c.x)} ${num(c.y)}`;
    else if (c.type === 'C') d += `C${num(c.x1)} ${num(c.y1)} ${num(c.x2)} ${num(c.y2)} ${num(c.x)} ${num(c.y)}`;
    else if (c.type !== 'Z') throw new Error(`unknown path command ${c.type}`);
  }
  d += d ? 'Z' : '';
  if (/NaN|Infinity|undefined/.test(d)) throw new Error('bad number in outlined path data');
  return d;
}

/** SVG path data for `text` laid out like <text>: kerning, letter-spacing, and text-anchor
 *  (middle centres the glyphs' ink box on x, so a letter sits optically centred). */
export function textPathData(text, { x, y, size, spacing = 0, anchor = 'start', font = LABEL_FONT }) {
  const opts = { kerning: true, letterSpacing: spacing / size };
  let dx = x;
  if (anchor !== 'start') {
    const b = font.getPath(text, 0, y, size, opts).getBoundingBox();
    dx = anchor === 'middle' ? x - (b.x1 + b.x2) / 2 : x - b.x2;
  }
  return pathData(font.getPath(text, dx, y, size, opts).commands);
}

function outline(svg, from) {
  const out = svg
    .replace(/<!--[\s\S]*?-->/, `<!-- Generated by scripts/build-icons.mjs from ${from}: text converted to outlines. Edit the source, not this file. -->`)
    .replace(/<text\b([^>]*)>([^<]*)<\/text>/g, (_, a, content) => {
      const t = attrsOf(a);
      const font = fontFor(t['font-family'], t['font-weight'] === 'bold' ? '700' : t['font-weight']);
      const d = textPathData(content.trim(), { x: +t.x, y: +t.y, size: +t['font-size'], spacing: +(t['letter-spacing'] || 0), anchor: t['text-anchor'] || 'start', font });
      const keep = Object.entries(t).filter(([k]) => !TEXT_ATTRS.has(k)).map(([k, v]) => ` ${k}="${v}"`).join('');
      return `<path d="${d}"${keep}/>`;
    });
  if (/<text\b/.test(out)) throw new Error(`${from}: <text> left after outlining`);
  return out;
}

/** The maskable icon: the master with its art scaled to 72%, centred, background full-bleed. */
function maskableFrom(master) {
  if (!master.includes('<g id="art">')) throw new Error('icon-master.svg needs a <g id="art"> group');
  return master
    .replace(/<!--[\s\S]*?-->/, '<!-- Maskable source, generated by scripts/build-icons.mjs from icon-master.svg: the art scaled to 72% so it stays inside Android\'s 80% safe zone (any circle or squircle mask). -->')
    .replace('<g id="art">', '<g id="art" transform="translate(100 100) scale(0.72) translate(-100 -100)">');
}

// ---------- 2. colours ----------

function checkColours(svg, name) {
  for (const [hex] of svg.matchAll(/#[0-9a-f]{6}\b/gi)) {
    if (!PALETTE.has(hex.toUpperCase())) throw new Error(`${name}: ${hex} is not a Wasabi and Nori token`);
  }
}

// ---------- 3. PNG, ICO ----------

const render = (svg, size) => new Resvg(svg, { fitTo: { mode: 'width', value: size }, font: { loadSystemFonts: false } }).render();

const CRC = Array.from({ length: 256 }, (_, n) => {
  let c = n;
  for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
  return c >>> 0;
});
function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}
function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}
/** An opaque RGB PNG (no alpha channel at all), for the iOS home-screen icon. */
function pngRGB(img) {
  const { width, height, pixels } = img;
  const row = width * 3 + 1;
  const raw = Buffer.alloc(row * height);
  for (let y = 0; y < height; y++) {
    for (let x = 0; x < width; x++) {
      const s = (y * width + x) * 4;
      if (pixels[s + 3] !== 255) throw new Error('apple-touch-icon must be fully opaque');
      pixels.copy(raw, y * row + 1 + x * 3, s, s + 3);
    }
  }
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // colour type: RGB
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
/** A multi-size .ico with PNG entries (supported by every current browser). */
function ico(entries) {
  const head = Buffer.alloc(6 + 16 * entries.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(entries.length, 4);
  let offset = head.length;
  entries.forEach(({ size, png }, i) => {
    const o = 6 + 16 * i;
    head[o] = size >= 256 ? 0 : size;
    head[o + 1] = size >= 256 ? 0 : size;
    head.writeUInt16LE(1, o + 4); // planes
    head.writeUInt16LE(32, o + 6); // bits per pixel
    head.writeUInt32LE(png.length, o + 8);
    head.writeUInt32LE(offset, o + 12);
    offset += png.length;
  });
  return Buffer.concat([head, ...entries.map((e) => e.png)]);
}

// ---------- 4. header mark ----------

/** The small icon's art (the S between its sidelines) as inline SVG for the header, every colour a
 *  var(--token). No tile or outline: the wasabi bar is the field. */
function headerMark(smallOutlined) {
  const art = smallOutlined.match(/<g id="art">([\s\S]*?)<\/g>/)[1];
  const tokenised = art.replace(/<(rect|line|path|circle)\b([^>]*?)\s*\/>/g, (_, tag, a) => {
    const t = attrsOf(a);
    const style = ['fill', 'stroke'].filter((k) => t[k]).map((k) => {
      const token = TOKEN_FOR[t[k].toUpperCase()];
      if (!token) throw new Error(`header mark: ${t[k]} has no icon token`);
      return `${k}:var(${token})`;
    }).join(';');
    const rest = Object.entries(t).filter(([k]) => k !== 'fill' && k !== 'stroke').map(([k, v]) => ` ${k}="${v}"`).join('');
    return `<${tag}${rest}${style ? ` style="${style}"` : ''}/>`;
  }).replace(/\n\s*/g, '');
  const svg = `<svg viewBox="0 0 200 200" xmlns="http://www.w3.org/2000/svg">${tokenised}</svg>`;
  return `// Generated by scripts/build-icons.mjs from assets/icon/icon-small.svg. Do not edit by hand.
// The brand mark in the header: the app icon's S between chalk sidelines, drawn straight on the
// wasabi bar (no tile). Colours are design tokens, so it follows tokens.css.
export const BRAND_MARK = '${svg}';
`;
}

// ---------- 5. launch screens, contact sheet ----------

// iPhone launch screens: [css width, css height, pixel ratio]
export const SPLASHES = [
  [440, 956, 3], [402, 874, 3], [430, 932, 3], [393, 852, 3], [390, 844, 3],
  [375, 812, 3], [360, 780, 3], [414, 896, 2], [375, 667, 2],
];
const inner = (svg) => svg.replace(/^[\s\S]*?<svg\b[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/<!--[\s\S]*?-->/g, '');
/** The master icon as a home-screen tile (iOS-like corner radius) at (x, y), size s. */
const tile = (masterOutlined, x, y, s, id) => `<defs><clipPath id="${id}"><rect width="200" height="200" rx="45"/></clipPath></defs>
  <svg x="${x}" y="${y}" width="${s}" height="${s}" viewBox="0 0 200 200"><g clip-path="url(#${id})">${inner(masterOutlined)}</g></svg>`;
function splashSvg(masterOutlined, w, h) {
  const s = Math.round(Math.min(w, h) * 0.3);
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
  <rect width="${w}" height="${h}" fill="${dark['--bg']}"/>${tile(masterOutlined, (w - s) / 2, (h - s) / 2, s, 'r')}</svg>`;
}

const uri = (png) => `data:image/png;base64,${png.toString('base64')}`;
const label = (text, x, y, size = 15, fill = '#5C6E68', anchor = 'start') => `<path d="${textPathData(text.toUpperCase(), { x, y, size, spacing: 1, anchor })}" fill="${fill}"/>`;

function contactSheet({ master, small, maskable }) {
  const sizes = [1024, 180, 64, 48, 32, 16];
  const png = (s) => render(s <= 48 ? small : master, s).asPng();
  const pngs = Object.fromEntries(sizes.map((s) => [s, png(s)]));
  const shown = (s) => (s === 1024 ? 256 : s);
  const backgrounds = [['on wasabi', light['--wasabi']], ['on white', '#FFFFFF'], ['on black', '#000000']];
  const gap = 28;
  const W = Math.max(140 + sizes.reduce((a, s) => a + shown(s) + gap, 0), 140 + 4 * (256 + gap)) + 20;
  let y = 70;
  const parts = [label('Sideline app icon: Sideline S', 24, 42, 26, '#0F1F1C')];
  for (const [name, bg] of backgrounds) {
    const h = 256 + 56;
    parts.push(`<rect x="0" y="${y}" width="${W}" height="${h}" fill="${bg}"/>`);
    parts.push(label(name, 24, y + 30, 16, bg === '#000000' ? '#9FB5AE' : '#0F1F1C'));
    let x = 140;
    for (const s of sizes) {
      const d = shown(s);
      parts.push(`<image x="${x}" y="${y + 20 + (256 - d) / 2}" width="${d}" height="${d}" href="${uri(pngs[s])}"/>`);
      const ink = bg === '#000000' ? '#9FB5AE' : '#0F1F1C';
      parts.push(label(`${s}${s === 1024 ? ' (at 1/4)' : ''}`, x, y + h - 26, 13, ink));
      if (s <= 48) parts.push(label('small', x, y + h - 10, 11, ink));
      x += d + gap;
    }
    y += h;
  }
  // Small sizes enlarged 4x, nearest-neighbour, to check the pixels.
  y += 20;
  parts.push(label('16, 32', 24, y + 30, 16, '#0F1F1C'), label('at 4x', 24, y + 50, 16, '#0F1F1C'));
  parts.push(`<image x="140" y="${y + 10}" width="64" height="64" href="${uri(pngs[16])}" image-rendering="optimizeSpeed"/>`);
  parts.push(`<image x="232" y="${y + 10}" width="128" height="128" href="${uri(pngs[32])}" image-rendering="optimizeSpeed"/>`);
  y += 160;
  // Maskable: as drawn, through a circle and a squircle, and with the 80% safe zone marked.
  const m = render(maskable, 512).asPng();
  parts.push(label('maskable', 24, y + 30, 16, '#0F1F1C'), label('512 at 1/2', 24, y + 50, 16, '#0F1F1C'));
  const mx = [140, 140 + 256 + gap, 140 + 2 * (256 + gap), 140 + 3 * (256 + gap)];
  parts.push(`<defs><clipPath id="circle"><circle cx="128" cy="128" r="128"/></clipPath><clipPath id="squircle"><rect width="256" height="256" rx="80"/></clipPath></defs>`);
  parts.push(`<image x="${mx[0]}" y="${y}" width="256" height="256" href="${uri(m)}"/>`);
  parts.push(`<g transform="translate(${mx[1]} ${y})"><image width="256" height="256" href="${uri(m)}" clip-path="url(#circle)"/></g>`);
  parts.push(`<g transform="translate(${mx[2]} ${y})"><image width="256" height="256" href="${uri(m)}" clip-path="url(#squircle)"/></g>`);
  parts.push(`<g transform="translate(${mx[3]} ${y})"><image width="256" height="256" href="${uri(m)}"/><circle cx="128" cy="128" r="102.4" fill="none" stroke="#EE5D45" stroke-width="2" stroke-dasharray="6 5"/></g>`);
  ['as drawn', 'circle mask', 'squircle mask', '80% safe zone'].forEach((t, i) => parts.push(label(t, mx[i], y + 256 + 24, 13, '#0F1F1C')));
  y += 256 + 44;
  const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${y}" viewBox="0 0 ${W} ${y}">
  <rect width="${W}" height="${y}" fill="${light['--bg']}"/>${parts.join('\n')}</svg>`;
  return new Resvg(sheet, { font: { loadSystemFonts: false } }).render().asPng();
}

// ---------- run ----------

const read = (f) => readFileSync(at(`${SRC}/${f}`), 'utf8');
const write = (f, data) => { writeFileSync(at(f), data); console.log('wrote', f); };

const masterSrc = read('icon-master.svg');
const smallSrc = read('icon-small.svg');
const maskableSrc = maskableFrom(masterSrc);
write(`${SRC}/icon-maskable.svg`, maskableSrc);
const master = outline(masterSrc, 'icon-master.svg');
const small = outline(smallSrc, 'icon-small.svg');
const maskable = outline(maskableSrc, 'icon-maskable.svg');
for (const [name, svg] of [['icon-master-outlined.svg', master], ['icon-small-outlined.svg', small], ['icon-maskable-outlined.svg', maskable]]) {
  checkColours(svg, name);
  write(`${SRC}/${name}`, svg);
}

const ICONS = [
  ['site/icons/icon-1024.png', master, 1024],
  ['site/icons/icon-512.png', master, 512],
  ['site/icons/icon-192.png', master, 192],
  ['site/icons/maskable-512.png', maskable, 512],
  ['site/icons/maskable-192.png', maskable, 192],
  ['site/icons/favicon-48.png', small, 48],
  ['site/icons/favicon-32.png', small, 32],
  ['site/icons/favicon-16.png', small, 16],
];
const out = {};
for (const [file, svg, size] of ICONS) {
  out[size + (svg === maskable ? 'm' : '')] = render(svg, size).asPng();
  write(file, out[size + (svg === maskable ? 'm' : '')]);
}
write('site/icons/apple-touch-icon.png', pngRGB(render(master, 180)));
write('site/favicon.ico', ico([16, 32, 48].map((size) => ({ size, png: out[size] }))));
write('site/icons/favicon.svg', small.replace(/ width="48" height="48"/, ''));
write('site/js/ui/brand-mark.js', headerMark(small));

const links = [];
for (const [w, h, dpr] of SPLASHES) {
  const file = `icons/splash-${w * dpr}x${h * dpr}.png`;
  write(`site/${file}`, render(splashSvg(master, w * dpr, h * dpr), w * dpr).asPng());
  links.push(`  <link rel="apple-touch-startup-image" media="screen and (device-width: ${w}px) and (device-height: ${h}px) and (-webkit-device-pixel-ratio: ${dpr}) and (orientation: portrait)" href="${file}">`);
}
for (const old of ['site/icons/icon-maskable-512.png', 'site/icons/icon.svg']) rmSync(at(old), { force: true });

mkdirSync(at('docs/screenshots/icon'), { recursive: true });
write('docs/screenshots/icon/contact-sheet.png', contactSheet({ master, small, maskable }));
console.log(`\nLaunch-screen links for index.html:\n${links.join('\n')}`);
