const STATE_LABEL = { predicted: 'Predicted', live: 'Live', final: 'Final' };

/** The brand mark in the brand bar: the app icon's S between chalk sidelines, drawn straight on
 *  the wasabi bar (generated by scripts/build-icons.mjs, token colours). */
export function brandBadge() {
  return frag(`<span class="brand-badge" aria-hidden="true">${BRAND_MARK}</span>`);
}

/**
 * App header: the wasabi brand bar (wordmark or back button, centre badge, action buttons) and
 * the ink title strip. `meta` may be a string or an element (updated in place by the caller).
 */
export function appHeader({ title, meta = null, back = null, actions = [] } = {}) {
  return h('header', { class: 'appbar' },
    h('div', { class: 'brandbar' },
      back ? backButton(back) : h('a', { class: 'wordmark', href: '#/', 'aria-label': 'Sideline: today' }, h('b', null, 'Side'), 'line'),
      brandBadge(),
      h('div', { class: 'bar-actions' }, actions)),
    h('div', { class: 'strip' }, h('h1', { class: 'strip-title' }, title), meta instanceof Node ? meta : meta ? h('span', { class: 'meta' }, meta) : null));
}

/** An icon button for the brand bar. */
export function barButton(name, label, onclick) {
  return h('button', { class: 'bar-btn', type: 'button', 'aria-label': label, onclick }, icon(name));
}

const HEX = /^#[0-9a-f]{6}$/i;
/** Team colour as a usable CSS colour (ESPN sends hex; missing or invalid falls back). */
export function teamColor(team, fallback = null) {
  const c = team?.color ? (String(team.color).startsWith('#') ? team.color : `#${team.color}`) : null;
  return c && HEX.test(c) ? c : fallback;
}

/** Team logo inside a ring of the team's colour (like the avatars on Ball.app). */
export function teamMark(team, size = '') {
  // Request each logo at about 3× its drawn size (rows ~18 px, lg ~40 px, posters ~48 px).
  const px = size === 'xl' ? 160 : size === 'lg' ? 128 : 80;
  return h('span', { class: `tlogo${size ? ` ${size}` : ''}`, style: { '--ring': teamColor(team) } }, logo(teamLogo(team), '', px));
}

/** Rating badge. `rating` may be null (unrated) and `pending` shows a spinner. */
export function badge(rating, { size = '', pending = false, onTap } = {}) {
  if (pending && !rating) {
    return h('span', { class: `badge pending ${size}`, 'aria-label': 'Rating loading' });
  }
  if (!rating) return h('span', { class: `badge none ${size}`, 'aria-label': 'Not rated' }, '—');
  const el = h('button', {
    class: `badge ${size}${pending ? ' refreshing' : ''}`,
    type: 'button',
    'data-band': rating.band.key,
    'data-state': rating.state,
    'aria-label': `${STATE_LABEL[rating.state]} excitement ${rating.value}, ${rating.band.label}. Tap for why.`,
  }, String(rating.value));
  el.addEventListener('click', (e) => {
    e.preventDefault();
    e.stopPropagation();
    if (onTap) onTap(); else openRatingSheet(rating);
  });
  return el;
}

/** Badge plus the likely range underneath for pre-game predictions. */
export function badgeWithRange(rating, opts = {}) {
  const b = badge(rating, opts);
  if (rating?.state !== 'predicted' || !rating.pred) return b;
  return h('span', { class: 'badge-col' }, b, h('span', { class: 'range' }, `${rating.pred.low}–${rating.pred.high}`));
}

const COMP_LABEL = {
  swing: 'Momentum swings', closeness: 'Late closeness', leadChanges: 'Lead changes', comeback: 'Comeback',
  novelty: 'Rare moments', pace: 'Scoring pace', stakes: 'Stakes', quality: 'Team quality',
  overtakes: 'On-track passes', finalGap: 'Fight for the win', incidents: 'Safety cars / flags', charge: 'Charge through the field',
};

let openSheet = null;

const SOURCE_LABEL = { market: 'betting odds', elo: 'team ratings (Elo)', none: 'schedule context' };

/** Range, P(Great), horizon and the point contribution of every pre-game term. */
function predictionBlock(p) {
  const terms = (p.terms || []).filter((t) => t.text && Math.abs(t.points) >= 0.5).sort((a, b) => b.points - a.points);
  return h('div', { class: 'pred-block' },
    h('p', { class: 'muted' },
      `${p.horizon?.label || 'Prediction'}: likely ${p.low}–${p.high} · ${Math.round(p.pGreat * 100)}% chance of Great · ${Math.round(p.pDull * 100)}% chance of Dull. Based on ${SOURCE_LABEL[p.source] || 'context'}; starts from a league base of ${Math.round(p.base)}.`),
    terms.length ? h('div', { class: 'terms' }, terms.map((t) => h('div', { class: 'term' },
      h('span', null, t.text),
      h('span', { class: t.points >= 0 ? 'pos' : 'neg' }, `${t.points >= 0 ? '+' : '−'}${Math.abs(t.points).toFixed(1)}`)))) : null,
    p.priorityParts?.length ? h('p', { class: 'tiny' }, `Watch Priority ${p.priority} (${p.priorityParts.map((x) => `+${x.points} ${x.label.toLowerCase()}`).join(', ')}): used for ordering only.`) : null,
    h('p', { class: 'tiny' }, 'Pre-game information explains only part of how exciting a game turns out, so the range matters more than the exact number.'),
  );
}

export function closeSheet() {
  if (!openSheet) return;
  const { sheet, backdrop } = openSheet;
  sheet.classList.remove('open');
  backdrop.classList.remove('open');
  setTimeout(() => { sheet.remove(); backdrop.remove(); }, 250);
  openSheet = null;
}

/** Bottom sheet explaining a rating in plain English. */
export function openRatingSheet(rating, { title = '', predicted = null } = {}) {
  closeSheet();
  const backdrop = h('div', { class: 'sheet-backdrop', onclick: closeSheet });
  const reasons = rating.reasons?.length ? rating.reasons : [{ text: 'Not much to report yet', tone: '-' }];
  const comps = rating.components ? Object.entries(rating.components) : [];
  const sheet = h('div', { class: 'sheet', role: 'dialog', 'aria-modal': 'true', 'aria-label': 'Why this rating' },
    h('div', { class: 'grab' }),
    h('div', { class: 'explain-head' },
      h('span', { class: 'badge lg', 'data-band': rating.band.key, 'data-state': rating.state }, String(rating.value)),
      h('div', null,
        h('h3', null, `${rating.band.label}`),
        h('div', { class: 'muted' }, `${STATE_LABEL[rating.state]} rating${rating.state === 'live' ? ' · updates as the game goes' : rating.state === 'final' ? ' · frozen' : ' · before the game'}`),
        title ? h('div', { class: 'tiny' }, title) : null)),
    h('ul', { class: 'reasons' }, reasons.map((r) => h('li', { class: r.tone === '-' ? 'neg' : '' }, r.text))),
    rating.pred ? predictionBlock(rating.pred) : null,
    predicted && rating.state !== 'predicted' ? h('p', { class: 'muted' }, `Predicted before the game: ${predicted.value} (${predicted.band.label}).`) : null,
    comps.length ? h('div', { class: 'comp-bars' }, comps.map(([k, v]) => h('div', { class: 'comp' },
      h('span', null, COMP_LABEL[k] || k),
      h('span', { class: 'bar' }, h('i', { style: { width: `${Math.round(v * 100)}%` } })),
      h('span', { class: 'tiny' }, Math.round(v * 100))))) : null,
    h('p', { class: 'tiny', style: { marginTop: '14px' } },
      '0–39 Dull · 40–64 OK · 65–84 Good · 85–100 Great. 50 is a median game for its league.'),
  );
  document.body.append(backdrop, sheet);
  requestAnimationFrame(() => { backdrop.classList.add('open'); sheet.classList.add('open'); });
  // Swipe down to close.
  let y0 = null;
  sheet.addEventListener('touchstart', (e) => { if (sheet.scrollTop <= 0) y0 = e.touches[0].clientY; }, { passive: true });
  sheet.addEventListener('touchmove', (e) => {
    if (y0 == null) return;
    const dy = e.touches[0].clientY - y0;
    if (dy > 0) sheet.style.transform = `translateY(${dy}px)`;
  }, { passive: true });
  sheet.addEventListener('touchend', (e) => {
    if (y0 == null) return;
    const dy = e.changedTouches[0].clientY - y0;
    sheet.style.transform = '';
    y0 = null;
    if (dy > 80) closeSheet();
  });
  openSheet = { sheet, backdrop };
}

document.addEventListener('keydown', (e) => { if (e.key === 'Escape') closeSheet(); });

/** Status text for a row: start time (PT), live clock, or final. */
export function statusInfo(game) {
  if (game.canceled) return { text: game.detail || 'Postponed', cls: 'final' };
  if (game.state === 'pre') return { text: formatTime(game.start), cls: '' };
  if (game.state === 'in') {
    let text = game.detail || 'Live';
    if (game.sport === 'soccer' && game.clock && !/half/i.test(text)) text = game.clock;
    return { text, cls: 'live' };
  }
  return { text: game.detail || 'Final', cls: 'final' };
}

export function watchInfo(game) {
  return whereToWatch(game.broadcasts, getSettings().services, game.league);
}

function teamLine(team, game, other, fav) {
  const final = game.state === 'post' && !game.canceled;
  const lost = final && team.score != null && other.score != null && (other.winner || (!team.winner && team.score < other.score));
  const showScore = game.state !== 'pre' && team.score != null;
  const isFav = fav && String(fav.id) === team.id;
  // Tennis players: no badge circle (it would only hold a flag), so the seed and name fit.
  const player = game.sport === 'tennis';
  return h('div', { class: `team-line${lost ? ' loser' : ''}${player ? ' no-mark' : ''}` },
    player ? null : teamMark(team),
    h('div', { class: 'team-name' },
      team.rank ? h('span', { class: 'rank' }, team.rank) : null,
      team.short || team.name,
      isFav ? h('span', { class: 'star', 'aria-label': 'Favorite' }, '★') : null,
      game.state === 'pre' && team.record ? h('span', { class: 'rec' }, team.record) : null),
    showScore ? h('div', { class: 'score' }, team.score) : h('span'),
  );
}

/**
 * One game row. `entry` = { game, rating, pending }.
 * @param {{showLeague?: boolean, onOpen: (game) => void}} opts
 */
export function gameRow(entry, { showLeague = false, onOpen } = {}) {
  const { game, rating, pending } = entry;
  const fav = favoriteFor(game);
  const st = statusInfo(game);
  const w = watchInfo(game);
  const lg = LEAGUE_BY_KEY[game.league];
  const circled = game.state === 'pre' && rating?.pred?.circle?.flagged;
  const sideBits = [
    showLeague ? h('div', { class: 'league-tag' }, sportIcon(lg.sport), lg.short) : null,
    h('div', { class: `status ${st.cls}` }, circled ? h('span', { class: 'circle-badge sm', title: `Circle this one: ${rating.pred.circle.reasons.join(', ')}` }, '◎') : null, st.text),
    w.status !== 'unknown' ? h('div', { class: `watch${w.status === 'none' ? ' none' : ''}` }, w.short) : null,
  ];
  // Optional leagues without a game page (NASCAR, tennis, UFC) are plain rows, not links.
  const link = (href) => (lg?.noGamePage
    ? { class: 'game-row static' }
    : { class: 'game-row', href, onclick: onOpen ? (e) => { e.preventDefault(); onOpen(game); } : null });
  if (game.sport === 'racing' || game.kind === 'event') {
    const podium = game.state === 'post' && game.drivers?.length
      ? game.drivers.slice(0, 3).map((d, i) => `${i + 1}. ${d.short || d.name}`).join('  ')
      : game.result || '';
    const mma = game.sport === 'mma';
    return h(lg?.noGamePage ? 'div' : 'a', link(`#/game/${game.league}/${encodeURIComponent(game.id)}?e=${game.eventId}`),
      lg?.scheduleOnly ? h('span', { class: 'badge none', title: 'Schedule only: not rated' }, '—')
        : game.isRace ? badgeWithRange(rating, { pending }) : h('span', { class: 'badge none', title: 'Only the race is rated' }, lg?.short || ''),
      h('div', { class: 'teams' },
        h('div', { class: 'race-title' }, mma ? game.shortName : `${game.shortName} · ${game.sessionLabel}`),
        h('div', { class: 'race-sub' }, mma ? [game.mainEvent, game.circuit].filter(Boolean).join(' · ') : game.circuit),
        podium ? h('div', { class: 'podium' }, podium) : null),
      h('div', { class: 'row-side' }, sideBits));
  }
  return h(lg?.noGamePage ? 'div' : 'a', link(`#/game/${game.league}/${encodeURIComponent(game.id)}`),
    fav ? h('span', { class: 'fav-flag', 'aria-hidden': 'true' }) : null,
    badgeWithRange(rating, { pending }),
    // Soccer lists the home side first (European convention); US sports list away @ home.
    h('div', { class: 'teams' }, game.sport === 'soccer'
      ? [teamLine(game.home, game, game.away, fav), teamLine(game.away, game, game.home, fav)]
      : [teamLine(game.away, game, game.home, fav), teamLine(game.home, game, game.away, fav)]),
    h('div', { class: 'row-side' }, sideBits),
  );
}

